-- Only the Edge Function's service role can execute this gateway. Client roles
-- have no table, key, or function access. No SECURITY DEFINER functions are used.
create schema if not exists store_private;
revoke all on schema store_private from public, anon, authenticated;
grant usage on schema store_private to service_role;

create table store_private.codes (
  id bigint generated by default as identity primary key,
  code_hash text unique not null check (code_hash ~ '^[a-f0-9]{64}$'),
  ciphertext bytea,
  label text not null,
  max_uses integer not null default 3 check (max_uses between 1 and 10000),
  used_count integer not null default 0 check (used_count >= 0 and used_count <= max_uses),
  active boolean not null default true,
  batch_id text,
  created_at timestamptz not null default now()
);
create index codes_batch_idx on store_private.codes(batch_id);
create table store_private.sessions (
  token uuid primary key default gen_random_uuid(),
  code_id bigint not null references store_private.codes(id),
  expires_at timestamptz not null default (now() + interval '24 hours'),
  completed_at timestamptz,
  created_at timestamptz not null default now()
);
create index sessions_code_idx on store_private.sessions(code_id);
create table store_private.results (
  id text primary key default replace(gen_random_uuid()::text, '-', '') check (id ~ '^[a-f0-9]{32}$'),
  session_token uuid unique references store_private.sessions(token),
  code_id bigint not null references store_private.codes(id),
  primary_id text not null,
  secondary_id text not null,
  scores jsonb not null,
  created_at timestamptz not null default now()
);
create index results_code_created_idx on store_private.results(code_id, created_at desc);
create index results_created_idx on store_private.results(created_at desc);
create table store_private.content (id int primary key check (id = 1), document jsonb not null, revision int not null default 0, updated_at timestamptz not null default now());
create table store_private.admins (email text primary key check (email = lower(email)));
create table store_private.encryption (id int primary key check (id = 1), secret text not null);
insert into store_private.encryption values (1, encode(extensions.gen_random_bytes(32), 'hex'));
create table store_private.audit (id uuid primary key default gen_random_uuid(), actor_email text not null, action text not null, summary text not null, created_at timestamptz not null default now());
create index audit_created_idx on store_private.audit(created_at desc);
create table store_private.rate_limits (bucket text primary key, count integer not null, expires_at timestamptz not null);
create index rate_limits_expires_idx on store_private.rate_limits(expires_at);

alter table store_private.codes enable row level security;
alter table store_private.sessions enable row level security;
alter table store_private.results enable row level security;
alter table store_private.content enable row level security;
alter table store_private.admins enable row level security;
alter table store_private.encryption enable row level security;
alter table store_private.audit enable row level security;
alter table store_private.rate_limits enable row level security;
revoke all on all tables in schema store_private from public, anon, authenticated;
grant all on all tables in schema store_private to service_role;
grant usage, select on all sequences in schema store_private to service_role;

create function store_private.code_json(c store_private.codes) returns jsonb
language sql stable security invoker set search_path = '' as $$
  select jsonb_build_object('id',c.id,'code',case when c.ciphertext is null then null else extensions.pgp_sym_decrypt(c.ciphertext,(select secret from store_private.encryption where id=1)) end,
    'label',c.label,'maxUses',c.max_uses,'usedCount',c.used_count,'active',c.active,'batchId',c.batch_id,'createdAt',c.created_at,'remainingUses',greatest(0,c.max_uses-c.used_count));
$$;
revoke all on function store_private.code_json(store_private.codes) from public, anon, authenticated;
grant execute on function store_private.code_json(store_private.codes) to service_role;

create function public.store_api(op text, p jsonb default '{}'::jsonb, actor uuid default null) returns jsonb
language plpgsql security invoker set search_path = '' as $$
declare
  c store_private.codes; s store_private.sessions; r store_private.results;
  v jsonb; items jsonb; batches jsonb; total bigint; n int; pg int;
  email text; batch text; plain text; k text; expected_revision int;
begin
  if current_user <> 'service_role' then raise exception '403:禁止访问'; end if;
  if op = 'rate' then
    delete from store_private.rate_limits where expires_at < now();
    insert into store_private.rate_limits values (p->>'bucket',1,now()+interval '11 minutes')
    on conflict(bucket) do update set count=store_private.rate_limits.count+1 returning count into n;
    return jsonb_build_object('allowed',n<=60);
  end if;
  if op = 'content' then return (select document from store_private.content where id=1); end if;
  if op = 'access' then
    update store_private.codes set used_count=used_count+1
      where code_hash=p->>'hash' and active and used_count<max_uses returning * into c;
    if not found then raise exception '403:密码无效、已停用或测试次数已用完'; end if;
    insert into store_private.sessions(code_id) values(c.id) returning * into s;
    return jsonb_build_object('sessionToken',s.token,'expiresAt',s.expires_at,'remainingUses',c.max_uses-c.used_count);
  end if;
  if op = 'submit' then
    select * into s from store_private.sessions where token=(p->>'sessionToken')::uuid for update;
    if not found then raise exception '403:本次测试不存在，请重新开始'; end if;
    select * into r from store_private.results where session_token=s.token;
    if found then return jsonb_build_object('resultId',r.id,'createdAt',r.created_at,'primaryId',r.primary_id,'secondaryId',r.secondary_id,'scores',r.scores); end if;
    if s.expires_at<=now() or s.completed_at is not null then raise exception '403:本次测试已失效，请重新开始'; end if;
    insert into store_private.results(session_token,code_id,primary_id,secondary_id,scores)
      values(s.token,s.code_id,p->>'primaryId',p->>'secondaryId',p->'scores') returning * into r;
    update store_private.sessions set completed_at=now() where token=s.token;
    return jsonb_build_object('resultId',r.id,'createdAt',r.created_at,'primaryId',r.primary_id,'secondaryId',r.secondary_id,'scores',r.scores);
  end if;
  if op = 'result' then
    select * into r from store_private.results where id=p->>'id';
    if not found then raise exception '404:没有找到这份报告'; end if;
    return jsonb_build_object('resultId',r.id,'createdAt',r.created_at,'primaryId',r.primary_id,'secondaryId',r.secondary_id,'scores',r.scores);
  end if;
  select lower(u.email) into email from auth.users u join store_private.admins a on lower(u.email)=a.email where u.id=actor and u.email_confirmed_at is not null and coalesce(u.is_anonymous,false)=false;
  if email is null then raise exception '403:此账号没有管理员权限'; end if;
  if op='admin/me' then return jsonb_build_object('email',email); end if;
  if op='admin/content' then return (select document from store_private.content where id=1); end if;
  if op='admin/save_content' then
    expected_revision=(p->>'revision')::int;
    v=jsonb_set(jsonb_set(p,'{revision}',to_jsonb(expected_revision+1)),'{updatedAt}',to_jsonb(now()));
    update store_private.content set document=v, revision=store_private.content.revision+1,updated_at=now() where id=1 and store_private.content.revision=expected_revision;
    if not found then raise exception '409:文案已在其他页面更新，请重新载入后再编辑'; end if;
    insert into store_private.audit(actor_email,action,summary) values(email,'update_content','发布题目及结果文案');
    return v;
  end if;
  if op='admin/generate' then
    batch=gen_random_uuid()::text;
    select secret into k from store_private.encryption where id=1;
    items='[]'::jsonb;
    for n in 1..(p->>'count')::int loop
      plain=(p->>'prefix')||'-'||upper(encode(extensions.gen_random_bytes(8),'hex'));
      insert into store_private.codes(code_hash,ciphertext,label,max_uses,batch_id)
        values(encode(extensions.digest(plain,'sha256'),'hex'),extensions.pgp_sym_encrypt(plain,k,'cipher-algo=aes256'),p->>'label',(p->>'maxUses')::int,batch);
      items=items||jsonb_build_array(plain);
    end loop;
    insert into store_private.audit(actor_email,action,summary) values(email,'generate_codes','生成'||(p->>'count')||'个密码；批次：'||(p->>'label'));
    return jsonb_build_object('batchId',batch,'codes',items,'count',(p->>'count')::int,'maxUses',(p->>'maxUses')::int,'label',p->>'label');
  end if;
  if op='admin/update_code' then
    select * into c from store_private.codes where id=(p->>'id')::bigint for update;
    if not found then raise exception '404:密码记录不存在'; end if;
    if p->>'action'='credit' then update store_private.codes set max_uses=max_uses+(p->>'amount')::int where id=c.id returning * into c;
    elsif p->>'action'='toggle' then update store_private.codes set active=(p->>'active')::boolean where id=c.id returning * into c;
    elsif p->>'action'='edit' then
      if (p->>'maxUses')::int<c.used_count then raise exception '409:总次数不能小于已用次数'; end if;
      update store_private.codes set label=p->>'label',max_uses=(p->>'maxUses')::int where id=c.id returning * into c;
    else raise exception '400:操作无效'; end if;
    insert into store_private.audit(actor_email,action,summary) values(email,p->>'action','修改密码#'||c.id);
    return store_private.code_json(c);
  end if;
  if op in ('admin/codes','admin/export') then
    pg=greatest(1,least(100000,coalesce((p->>'page')::int,1)));
    select count(*) into total from store_private.codes a where
      (coalesce(p->>'q','')='' or position(lower(p->>'q') in lower(a.label))>0 or a.id::text=p->>'q' or position(p->>'q' in coalesce(a.batch_id,''))>0)
      and (coalesce(p->>'codeHash','')='' or a.code_hash=p->>'codeHash')
      and (coalesce(p->>'batch','')='' or a.batch_id=p->>'batch')
      and (coalesce(p->>'status','all')='all' or (p->>'status'='available' and a.active and a.used_count<a.max_uses) or (p->>'status'='disabled' and not a.active) or (p->>'status'='exhausted' and a.used_count>=a.max_uses));
    if op='admin/export' and total>2000 then raise exception '400:单次最多导出2000条，请先筛选'; end if;
    select coalesce(jsonb_agg(a.item),'[]'::jsonb) into items from (
      select store_private.code_json(a) as item from store_private.codes a where
        (coalesce(p->>'q','')='' or position(lower(p->>'q') in lower(a.label))>0 or a.id::text=p->>'q' or position(p->>'q' in coalesce(a.batch_id,''))>0)
        and (coalesce(p->>'codeHash','')='' or a.code_hash=p->>'codeHash') and (coalesce(p->>'batch','')='' or a.batch_id=p->>'batch')
        and (coalesce(p->>'status','all')='all' or (p->>'status'='available' and a.active and a.used_count<a.max_uses) or (p->>'status'='disabled' and not a.active) or (p->>'status'='exhausted' and a.used_count>=a.max_uses))
      order by id desc limit case when op='admin/export' then 2000 else 20 end offset case when op='admin/export' then 0 else (pg-1)*20 end
    ) a;
    select coalesce(jsonb_agg(b),'[]'::jsonb) into batches from (select batch_id as id,min(label) as label,count(*) as count from store_private.codes where batch_id is not null group by batch_id order by max(created_at) desc limit 100) b;
    if op='admin/export' then insert into store_private.audit(actor_email,action,summary) values(email,'export_codes','导出'||total||'条密码记录'); end if;
    return jsonb_build_object('items',items,'batches',batches,'total',total,'page',pg,'pageSize',20);
  end if;
  if op='admin/records' then
    pg=greatest(1,least(100000,coalesce((p->>'page')::int,1)));
    select count(*) into total from store_private.results where coalesce(p->>'codeId','')='' or code_id::text=p->>'codeId';
    select coalesce(jsonb_agg(a),'[]'::jsonb) into items from (select r.id,r.code_id as "codeId",c.label,r.primary_id as "primaryId",r.secondary_id as "secondaryId",r.scores,r.created_at as "createdAt" from store_private.results r join store_private.codes c on c.id=r.code_id where coalesce(p->>'codeId','')='' or r.code_id::text=p->>'codeId' order by r.created_at desc limit 20 offset (pg-1)*20) a;
    return jsonb_build_object('items',items,'total',total,'page',pg,'pageSize',20);
  end if;
  if op='admin/audit' then
    select coalesce(jsonb_agg(a),'[]'::jsonb) into items from (select actor_email as "actorEmail",action,summary,created_at as "createdAt" from store_private.audit order by created_at desc limit 100) a;
    return jsonb_build_object('items',items);
  end if;
  if op='admin/overview' then
    return jsonb_build_object(
      'codes',(select jsonb_build_object('total',count(*),'available',count(*) filter(where active and used_count<max_uses),'disabled',count(*) filter(where not active),'remaining',coalesce(sum(max_uses-used_count) filter(where active),0)) from store_private.codes),
      'results',(select jsonb_build_object('total',count(*),'today',count(*) filter(where (created_at at time zone 'Asia/Shanghai')::date=(now() at time zone 'Asia/Shanghai')::date)) from store_private.results),
      'sessions',(select jsonb_build_object('total',count(*)) from store_private.sessions),
      'days',(select coalesce(jsonb_agg(a),'[]'::jsonb) from (select (created_at at time zone 'Asia/Shanghai')::date as day,count(*) as count from store_private.results where created_at>=now()-interval '14 days' group by day order by day) a),
      'grouped',(select coalesce(jsonb_agg(a),'[]'::jsonb) from (select scores,count(*) as count from store_private.results group by scores) a),
      'activity',(select coalesce(jsonb_agg(a),'[]'::jsonb) from (select action,summary,created_at as "createdAt" from store_private.audit order by created_at desc limit 8) a),
      'today',(now() at time zone 'Asia/Shanghai')::date
    );
  end if;
  raise exception '404:功能不存在';
end;
$$;
revoke all on function public.store_api(text,jsonb,uuid) from public, anon, authenticated;
grant execute on function public.store_api(text,jsonb,uuid) to service_role;
